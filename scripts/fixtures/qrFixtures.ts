/**
 * Real QR codes, as module matrices.
 *
 * Generated once with CoreImage (tools/qrgen.swift) and checked in as text, so
 * the suite needs no encoder, no image decoding and no network — and so the
 * fixture is a genuine spec-conformant code rather than something we drew.
 * Each row is one module row: '#' dark, '.' light, no quiet zone.
 */

export interface QrFixture {
  /** The exact string the code decodes to. */
  payload: string;
  /** Module rows. Side length is 4 * version + 17. */
  rows: string[];
}

